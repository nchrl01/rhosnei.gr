// CC0 sampled piano. Meaningful moves and known quiet intervals select single notes.
import {createPianoPhrasing,pianoNuance} from './piano-phrasing.js?v=59';
import {createPianoPolicy} from './piano-policy.js?v=59';
const unit=n=>Math.max(0,Math.min(1,Number(n)||0));
let sampleDownload;
async function loadSampleAsset(path,format){
 const controller=new AbortController(),timeout=setTimeout(()=>controller.abort(),20000);
 try{
  const response=await fetch('samples/piano/'+path+'?v=59',{signal:controller.signal});
  if(!response.ok)throw Error('Cannot load piano asset '+path);
  return await response[format]();
 }finally{clearTimeout(timeout);}
}
// Start downloading when a market is selected, before the audio gesture. A
// missing sample must not silence all the other, successfully loaded notes.
export function preloadPianoSamples(){
 if(!sampleDownload)sampleDownload=(async()=>{
  const manifest=await loadSampleAsset('manifest.json','json');
  const results=await Promise.allSettled(manifest.files.map(async item=>{
   return {...item,bytes:await loadSampleAsset(item.file,'arrayBuffer')};
  }));
  const samples=results.filter(result=>result.status==='fulfilled').map(result=>result.value);
  if(!samples.length)throw Error('Piano samples unavailable');
  return samples;
 })().catch(error=>{sampleDownload=null;throw error;});
 return sampleDownload;
}
export function marketResonance(cap){
 const value=Number(cap);
 return value>0&&Number.isFinite(value)?unit((Math.log10(value)-4)/4):0;
}
export async function createTradePiano(ctx,destination,{onVoice=()=>{},onArpeggio=()=>{}}={}){
 const downloaded=await preloadPianoSamples();
 // Mono, short assets are normalized offline. Startup no longer scans every
 // decoded sample on the main thread while the Pd engine is already sounding.
 const decoded=await Promise.allSettled(downloaded.map(async item=>({midi:item.midi,trim:Number(item.trim)||1,buffer:await ctx.decodeAudioData(item.bytes.slice(0))})));
 const samples=decoded.filter(result=>result.status==='fulfilled').map(result=>result.value);
 if(!samples.length)throw Error('This browser could not decode the piano samples');
 const input=ctx.createGain(),filter=ctx.createBiquadFilter(),dry=ctx.createGain(),wet=ctx.createGain(),room=ctx.createConvolver(),tailGate=ctx.createGain(),master=ctx.createGain();
 // A soft piano source blooms into a continuous room tail. The longer room
 // is created once, rather than regenerated by frames or market-cap changes.
 filter.type='lowpass';filter.frequency.value=2200;filter.Q.value=.55;
 dry.gain.value=.4;wet.gain.value=.55;master.gain.value=0;
 // At ordinary phone sample rates this is 4.8 seconds; cap unusually high
 // device rates at 3.84 MB for the two floating-point impulse channels.
 const impulse=ctx.createBuffer(2,Math.min(480000,Math.ceil(ctx.sampleRate*4.8)),ctx.sampleRate);
 let noise=1917;
 for(let channel=0;channel<2;channel++){
  const data=impulse.getChannelData(channel);let smooth=0,diffuse=0;
  for(let i=0;i<data.length;i++){
   noise=(Math.imul(noise,1664525)+1013904223)>>>0;
   smooth=.84*smooth+.16*(noise/2147483648-1);diffuse=.96*diffuse+.04*smooth;
   const t=i/ctx.sampleRate,bloom=Math.min(1,t/.065),fade=Math.min(1,(data.length-1-i)/(ctx.sampleRate*.6));
   data[i]=(.65*smooth+.35*diffuse)*bloom*Math.exp(-t*1.08)*fade;
  }
 }
 room.buffer=impulse;input.connect(filter);filter.connect(dry);filter.connect(room);room.connect(wet);dry.connect(tailGate);wet.connect(tailGate);tailGate.connect(master);master.connect(destination);
 let enabled=true,running=false,volume=.5,seed=1917,closed=false,arp=null,pattern=[],nextArp=0,lastArpBucket=null,roomDirty=false,roomTimer=null,reopenAt=0,lastResonance=-1;
 const policy=createPianoPolicy(seed);
 const phrasing=createPianoPhrasing(seed);
 const voices=new Set();
 function updateGain(){master.gain.setTargetAtTime(enabled&&running?volume:0,ctx.currentTime,.025);}
 function hold(param,time){
  if(param.cancelAndHoldAtTime)param.cancelAndHoldAtTime(time);
  else{const value=param.value;param.cancelScheduledValues(time);param.setValueAtTime(value,time);}
 }
 function stopVoice(voice){
  if(voice.fading)return;voice.fading=true;
  const time=ctx.currentTime;hold(voice.gain.gain,time);voice.gain.gain.linearRampToValueAtTime(0,time+.035);
  try{voice.source.stop(time+.04);}catch{}
 }
 function clear(){
  arp=null;for(const voice of voices)stopVoice(voice);
  if(!roomDirty)return;
  clearTimeout(roomTimer);const time=ctx.currentTime;reopenAt=time+.075;
  hold(tailGate.gain,time);tailGate.gain.linearRampToValueAtTime(0,time+.035);
  // Keep the output gate shut until the room is actually cleared. A late
  // main-thread callback cannot reset a still-audible convolution buffer.
  roomTimer=setTimeout(()=>{roomTimer=null;if(closed)return;room.buffer=null;room.buffer=impulse;roomDirty=[...voices].some(voice=>!voice.fading);
   const now=ctx.currentTime;hold(tailGate.gain,now);tailGate.gain.linearRampToValueAtTime(1,now+.02);
  },55);
 }
 function note(midi,time,dynamics,duration=4.4,kind='note',attack=.018){
  const active=[...voices].filter(voice=>!voice.fading);
  while(active.length>=6)stopVoice(active.shift());
  time=Math.max(time,reopenAt,ctx.currentTime+.012);
  const sample=samples.reduce((a,b)=>Math.abs(a.midi-midi)<=Math.abs(b.midi-midi)?a:b);
  const source=ctx.createBufferSource(),gain=ctx.createGain();source.buffer=sample.buffer;source.playbackRate.value=2**((midi-sample.midi)/12);
  duration=Math.min(duration,source.buffer.duration/source.playbackRate.value);
  const end=time+duration,peak=dynamics*sample.trim,release=Math.min(kind==='arp'?.9:1.6,duration*.4);
  // Mask the sampled hammer transient while preserving seeded touch. Even a
  // stolen voice still uses stopVoice's independent, click-free release.
  const swell=Math.min(kind==='arp'?Math.max(.055,attack*4):Math.max(.11,attack*8),duration*.2);
  gain.gain.setValueAtTime(0,time);gain.gain.linearRampToValueAtTime(peak,time+swell);gain.gain.setValueAtTime(peak,end-release);gain.gain.linearRampToValueAtTime(0,end-.002);
  source.connect(gain);gain.connect(input);const voice={source,gain,kind,fading:false};voices.add(voice);roomDirty=true;source.onended=()=>{source.disconnect();gain.disconnect();voices.delete(voice);};source.start(time);source.stop(end);
  return time;
 }
 // Audio-clock lookahead keeps attacks independent of the drawing frame rate.
 // Only a triggered four-beat phrase is scheduled; this never free-runs.
 const scheduler=setInterval(()=>{
  if(!arp||closed||!running||!enabled||ctx.state!=='running')return;
  while(arp.index<arp.notes.length&&arp.nextTime<ctx.currentTime+.12){
   const [step,pitch]=arp.notes[arp.index++],time=arp.nextTime;arp.nextTime+=arp.step;if(time<ctx.currentTime-.08)continue;
   const notes=arp.harmony;if(!notes?.length)break;
   const target=notes.reduce((sum,n)=>sum+n,0)/notes.length+9+(pitch-66)*.5;
   const candidates=notes.flatMap(n=>[n,n+12,n+24]).filter(n=>n>=48&&n<=81);
   const cost=n=>Math.abs(n-target)+(arp.previous===null?0:Math.abs(n-arp.previous)*.45);
   const midi=candidates.reduce((a,b)=>cost(a)<=cost(b)?a:b),nuance=pianoNuance(arp.seed,step);
   arp.previous=midi;
   const sounded=note(midi,time+nuance.delay,arp.gain*nuance.velocity,2.7*nuance.duration,'arp',nuance.attack);onArpeggio({midi,step,time:sounded,tempo:arp.tempo});
  }
  if(arp.index>=arp.notes.length)arp=null;
 },25);
 function play(selection,event,cap,music){
  const quiet=selection.reason==='quiet',phrase=phrasing.next(event,music,{quiet,changePct:selection.changePct});
  const {midi,harmony}=phrase,intensity=unit(music.intensity);
  const time=note(midi,ctx.currentTime+phrase.delay,(quiet?.105:.20*(.7+.3*intensity))*phrase.velocity,(quiet?4:4.6)*phrase.duration,'note',phrase.attack);
  const bucket=Number.isFinite(event.chordStep)?event.chordStep:Math.floor(selection.at/30000);
  const draw=(Math.imul((seed^bucket)>>>0,2654435761)>>>0)%4;
  // The existing occasional AI phrase is allowed only after a significant move.
  // Quiet notes never start a phrase or a chord.
  if(!quiet&&pattern.length&&intensity>.015&&!arp&&time>=nextArp&&bucket!==lastArpBucket&&draw===0){
   const tempo=Math.max(40,Math.min(140,Number(music.tempo)||40)),beat=60/tempo;
   const notes=pattern.filter((_,i)=>i%2===0||pattern.length<=8).slice(0,8).map(([,pitch],i)=>[i,pitch]);
   arp={notes,index:0,nextTime:time+beat,step:beat/2,tempo,gain:.075*(.6+.4*intensity),harmony:[...harmony.notes],seed:(seed^bucket)>>>0,previous:null};nextArp=time+beat*24;lastArpBucket=bucket;
  }
  onVoice({id:event.id,notes:[midi],harmony,resonance:marketResonance(cap),reason:selection.reason,changePct:selection.changePct,at:selection.at});
  return true;
 }
 return {
  setMaster(value){volume=unit(value);updateGain();},
  setRunning(value){running=Boolean(value);updateGain();if(!running)clear();},
  setEnabled(value){enabled=Boolean(value);updateGain();if(!enabled)clear();},
  reset(value=seed){clear();seed=Number(value)>>>0;policy.reset(seed);phrasing.reset(seed);nextArp=0;lastArpBucket=null;},
  setArpeggioPattern(value){pattern=Array.isArray(value)?value.map(row=>[...row]):[];},
  setTempo(value){if(arp){arp.tempo=Math.max(40,Math.min(140,Number(value)||40));arp.step=30/arp.tempo;}},
  resonance(cap){const r=marketResonance(cap);if(Math.abs(r-lastResonance)>.0001){lastResonance=r;filter.Q.setTargetAtTime(.55+1.4*r,ctx.currentTime,.8);filter.frequency.setTargetAtTime(2200-500*r,ctx.currentTime,.8);dry.gain.setTargetAtTime(.4-.08*r,ctx.currentTime,.8);wet.gain.setTargetAtTime(.55+.13*r,ctx.currentTime,.8);}return r;},
  trade(event,cap,music=event.music||{}){
   if(closed||!enabled||!running||ctx.state!=='running')return false;
   this.resonance(cap);
   this.setTempo(music.tempo);
   const selection=policy.trade({...event,quietAt:ctx.currentTime*1000},music);
   return selection?play(selection,event,cap,music):false;
  },
  frame(m,{playing=false,seeking=false,ended=false,at,price,known=false,quiet=false,referencePrice}={}){
   if(closed||!enabled||!running||!playing||seeking||ended||ctx.state!=='running')return false;
   const selection=policy.idle({at,quietAt:ctx.currentTime*1000,price,music:m.music,known,quiet,referencePrice});
   return selection?play(selection,{id:'quiet:'+selection.at,at:selection.at},m.context?.latestCap,m.music||{}):false;
  },
  close(){closed=true;clearInterval(scheduler);clearTimeout(roomTimer);arp=null;master.gain.setTargetAtTime(0,ctx.currentTime,.012);for(const voice of voices)stopVoice(voice);setTimeout(()=>{for(const node of [input,filter,dry,wet,room,tailGate,master])node.disconnect();},50);},
 };
}
